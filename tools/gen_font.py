order = list(GLYPHS.keys())
COLS = 16
CELL_W, CELL_H = 6, 8          # 5x7 glyph + 1px padding right/bottom
rows_needed = (len(order) + COLS - 1) // COLS
W, H = COLS * CELL_W, rows_needed * CELL_H

# --- build RGBA pixel buffer (white ink, transparent elsewhere) ---
px = bytearray(W * H * 4)
placements = []  # (codepoint, x, y)
for idx, key in enumerate(order):
    gx = (idx % COLS) * CELL_W
    gy = (idx // COLS) * CELL_H
    for ry, rowstr in enumerate(GLYPHS[key]):
        for rx, ch in enumerate(rowstr):
            if ch == "#":
                o = ((gy + ry) * W + (gx + rx)) * 4
                px[o:o+4] = b"\xff\xff\xff\xff"
    placements.append((ord(key), gx, gy))

def _chunk(tag, data):
    c = tag + data
    return struct.pack(">I", len(data)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)

raw = bytearray()
for y in range(H):
    raw.append(0)
    raw += px[y*W*4:(y+1)*W*4]
png = (b"\x89PNG\r\n\x1a\n"
       + _chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 6, 0, 0, 0))
       + _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
       + _chunk(b"IEND", b""))
open(os.path.join(OUT, "pixel5x7.png"), "wb").write(png)

# --- AngelCode .fnt (text). base at glyph bottom; simple monospace advance. ---
